//! Emits `AnkiBackend+Services.swift`: one typed async method per backend RPC.
//!
//! Service and method indices MUST come from `anki_proto_gen::get_services`,
//! the same function rslib's dispatcher is generated from. Hand-numbering
//! them, or using descriptor order, silently calls the wrong method.
//!
//! Usage: swiftgen <descriptors.bin> <output.swift>

use std::fmt::Write as _;
use std::fs;

use anki_proto_gen::get_services;
use anki_proto_gen::BackendService;
use anki_proto_gen::Method;
use anyhow::bail;
use anyhow::Context;
use anyhow::Result;
use prost_reflect::DescriptorPool;
use prost_reflect::MessageDescriptor;

/// Services the Rust dispatcher doesn't route, or that are AnkiDroid-specific.
const SKIPPED_SERVICES: &[&str] = &["BackendFrontendService", "BackendAnkidroidService"];

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    let (descriptors, output) = match args.as_slice() {
        [_, d, o] => (d.clone(), o.clone()),
        _ => bail!("usage: swiftgen <descriptors.bin> <output.swift>"),
    };
    let bytes = fs::read(&descriptors).with_context(|| format!("reading {descriptors}"))?;
    let pool = DescriptorPool::decode(bytes.as_ref())?;
    let (_, services) = get_services(&pool);

    let mut out = String::new();
    out.push_str(HEADER);
    let mut count = 0;
    for service in &services {
        if SKIPPED_SERVICES.contains(&service.name.as_str()) {
            continue;
        }
        writeln!(out, "\n// MARK: - {}\n", service.name)?;
        writeln!(out, "extension AnkiBackend {{")?;
        for method in service.all_methods() {
            render_method(service, method, &mut out)?;
            count += 1;
        }
        writeln!(out, "}}")?;
    }
    fs::write(&output, out).with_context(|| format!("writing {output}"))?;
    eprintln!("swiftgen: wrote {count} methods to {output}");
    Ok(())
}

const HEADER: &str = "\
// GENERATED by rust/swiftgen from Anki's protobuf descriptors. DO NOT EDIT.
// Regenerate with scripts/gen-swift.sh after bumping vendor/anki.

import Foundation
import SwiftProtobuf
";

fn render_method(service: &BackendService, method: &Method, out: &mut String) -> Result<()> {
    let input = method.input();
    let output = method.output();
    let name = swift_identifier(&lower_camel(&method.name));
    if let Some(comments) = &method.comments {
        for line in comments.lines() {
            writeln!(out, "    /// {}", line.trim())?;
        }
    }

    let params = match &input {
        Some(msg) => format!("_ input: {}", swift_type(msg)?),
        None => String::new(),
    };
    let ret = match &output {
        Some(msg) => format!(" -> {}", swift_type(msg)?),
        None => String::new(),
    };
    let input_expr = if input.is_some() {
        "input"
    } else {
        "Anki_Generic_Empty()"
    };
    let call = if output.is_some() {
        "try await run"
    } else {
        "_ = try await run"
    };
    let as_type = match &output {
        Some(msg) => format!(", as: {}.self", swift_type(msg)?),
        None => ", as: Anki_Generic_Empty.self".to_string(),
    };

    writeln!(
        out,
        "    @discardableResult\n    public func {name}({params}) async throws{ret} {{\n        \
         {call}(service: {svc}, method: {m}, input: {input_expr}{as_type})\n    }}\n",
        svc = service.index,
        m = method.index,
    )?;
    // Drop the attribute when there's nothing to discard.
    if output.is_none() {
        let fixed = out.replace(
            &format!("    @discardableResult\n    public func {name}("),
            &format!("    public func {name}("),
        );
        *out = fixed;
    }
    Ok(())
}

/// Mirror SwiftProtobuf's naming: package `anki.deck_config` becomes the
/// prefix `Anki_DeckConfig_`, nested messages are joined with `.`.
fn swift_type(msg: &MessageDescriptor) -> Result<String> {
    let package = msg.package_name();
    let prefix: String = package
        .split('.')
        .map(upper_camel)
        .collect::<Vec<_>>()
        .join("_");
    let relative = msg
        .full_name()
        .strip_prefix(package)
        .and_then(|s| s.strip_prefix('.'))
        .context("message outside its package")?;
    let mut parts = relative.split('.');
    let top = parts.next().context("empty message name")?;
    let nested: Vec<&str> = parts.collect();
    if nested
        .iter()
        .any(|n| SWIFT_PROTOBUF_RENAMED_NESTED.contains(n))
    {
        // SwiftProtobuf appends "Message" to these; bail rather than emit a
        // type name that won't compile.
        bail!("nested type name needs escaping: {}", msg.full_name());
    }
    let mut name = format!("{prefix}_{top}");
    for n in nested {
        name.push('.');
        name.push_str(n);
    }
    Ok(name)
}

/// Nested type names that SwiftProtobuf renames (subset relevant to RPC types).
const SWIFT_PROTOBUF_RENAMED_NESTED: &[&str] = &["Type", "Protocol", "Self", "Any", "Error"];

fn upper_camel(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn lower_camel(snake: &str) -> String {
    let upper = upper_camel(snake);
    let mut c = upper.chars();
    match c.next() {
        Some(f) => f.to_lowercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

fn swift_identifier(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "case", "catch", "class", "continue", "default", "defer", "do", "else",
        "enum", "extension", "fallthrough", "false", "for", "func", "guard", "if", "import", "in",
        "init", "inout", "internal", "is", "let", "nil", "operator", "private", "protocol",
        "public", "repeat", "return", "self", "static", "struct", "subscript", "super", "switch",
        "throw", "throws", "true", "try", "typealias", "var", "where", "while",
    ];
    if KEYWORDS.contains(&name) {
        format!("`{name}`")
    } else {
        name.to_string()
    }
}

